/**
 * Build the browser half: bundle src/client/entry.jsx with esbuild and wrap it
 * in the module-loader envelope the Harness web client expects.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..')
const entry = path.join(root, 'src', 'client', 'entry.jsx')
const tmp = path.join(root, '.build-client.cjs')
const out = path.join(root, 'client.js')

const flags = [
  entry,
  '--bundle',
  '--format=cjs',
  '--platform=browser',
  '--external:react',
  '--loader:.css=text',
  '--jsx=transform',
  '--target=es2020',
  '--minify',
  `--outfile=${tmp}`,
]

const explicit = process.env.ESBUILD
if (explicit) execFileSync(explicit, flags, { stdio: 'inherit', cwd: root })
else execFileSync('npx', ['--yes', 'esbuild@0.25.10', ...flags], { stdio: 'inherit', cwd: root })

const bundle = fs.readFileSync(tmp, 'utf8')
const wrapped = `/* dsh-lemo-studio client module — generated by scripts/build.mjs. Do not edit by hand. */
window.__ModuleLoader__.load({
  id: 'dsh-lemo-studio',
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${bundle}
    return module.exports;
  },
});
`
fs.writeFileSync(out, wrapped)
fs.rmSync(tmp, { force: true })
console.log(`wrote ${path.relative(root, out)} (${wrapped.length} bytes)`)
